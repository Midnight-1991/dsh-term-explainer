#!/usr/bin/env node
/**
 * Embed data/external-glossary.json into client.js between marker comments.
 *
 *   node scripts/embed-external-glossary.mjs
 *
 * The generated block is the only part of client.js that is machine-written.
 * Edit curated entries (the GLOSSARY array above the markers) by hand; edit the
 * upstream imports by re-running scripts/sync-external-glossary.mjs.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const clientPath = join(root, 'client.js');
const dataPath = join(root, 'data/external-glossary.json');

const BEGIN = '      /* EXTERNAL-GLOSSARY:BEGIN generated by scripts/embed-external-glossary.mjs - do not edit by hand */';
const END = '      /* EXTERNAL-GLOSSARY:END */';

const data = JSON.parse(readFileSync(dataPath, 'utf8'));
let client = readFileSync(clientPath, 'utf8');

/* Curated rows are hand-written in client.js: read them to avoid duplicating terms. */
const glossaryMatch = /const GLOSSARY = \[([\s\S]*?)\n      \];/.exec(client);
if (!glossaryMatch) throw new Error('cannot locate the curated GLOSSARY array in client.js');
const curated = new Function(`return [${glossaryMatch[1]}];`)();
if (!Array.isArray(curated) || curated.length < 100) throw new Error('curated GLOSSARY looks wrong');

const normalize = (value) =>
  String(value)
    .toLowerCase()
    .replace(/[（(][^）)]*[）)]/g, '')
    .replace(/[\s_-]/g, '');

const keys = new Set();
const addKeys = (row) => {
  for (const value of [row[0], row[1], ...((row[4] && row[4].aliases) || [])]) {
    const key = normalize(value || '');
    if (key) keys.add(key);
  }
};

for (const row of curated) addKeys(row);

const kept = [];
const dropped = [];
for (const row of data.entries) {
  const rowKeys = [row[0], row[1], ...((row[4] && row[4].aliases) || [])].map((value) => normalize(value || '')).filter(Boolean);
  if (rowKeys.some((key) => keys.has(key))) {
    dropped.push(row[0]);
    continue;
  }
  rowKeys.forEach((key) => keys.add(key));
  kept.push(row);
}

const sources = data.sources
  .map((source) => `${source.id} (${source.license}, ${source.added} entries @ ${String(source.commit).slice(0, 8)})`)
  .join(', ');
const lines = kept.map((row) => `        ${JSON.stringify(row)},`);
const block = [
  BEGIN,
  `      /* Sources: ${sources}. See THIRD_PARTY_NOTICES.md and data/external-glossary.json. */`,
  '      const EXTERNAL_GLOSSARY = [',
  ...lines,
  '      ];',
  '      const EXTERNAL_GLOSSARY_TOTAL = EXTERNAL_GLOSSARY.length;',
  END,
].join('\n');

let next;
if (client.includes(BEGIN)) {
  next = client.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), block);
} else {
  const anchor = /const EMPTY_OPTIONS = Object\.freeze\(\{\}\);\n/;
  if (!anchor.test(client)) throw new Error('cannot locate insertion anchor in client.js');
  next = client.replace(anchor, `${block}\n\n$&`);
}

writeFileSync(clientPath, next);
console.log(`embedded ${kept.length} external entries (skipped ${dropped.length} duplicates), client.js now ${next.length} chars`);
if (dropped.length) console.log('skipped:', dropped.join(', '));
